"""Refresh the release builder's exact wheel hashes from PyPI; enforce the two-week rule."""

import argparse
import hashlib
import json
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
TOOLS = {
    "build-constraints.txt": {"uv_build": "0.13.1"},
    "docopt-build-requirements.txt": {"pip": "26.2.2", "setuptools": "84.1.0"},
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--security-exception", choices=["setuptools==84.1.0"], help="Only after a reviewed security cooldown exception"
    )
    args = parser.parse_args()
    cutoff = datetime.now(timezone.utc) - timedelta(days=14)
    for filename, packages in TOOLS.items():
        lines = ["# Generated by scripts/lock-build-tools.py; review versions, dates and SHA-256 values."]
        for name, version in packages.items():
            # Fixed HTTPS PyPI endpoint, with package/version chosen in this file.
            with urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as response:  # nosec B310
                metadata = json.load(response)
            wheels = [item for item in metadata["urls"] if item["filename"].endswith(".whl") and not item["yanked"]]
            if not wheels:
                raise ValueError(f"No published wheels for {name} {version}")
            if any(
                datetime.fromisoformat(item["upload_time_iso_8601"].replace("Z", "+00:00")) > cutoff for item in wheels
            ):
                if args.security_exception != f"{name}=={version}":
                    raise ValueError(f"{name} {version} has a wheel younger than two weeks; maintainer review required")
                lines.append(
                    f"# Reviewed security cooldown exception: {name}=={version}; record maintainer approval in the PR."
                )
            hashes = sorted({item["digests"]["sha256"] for item in wheels})
            if any(len(digest) != hashlib.sha256().digest_size * 2 for digest in hashes):
                raise ValueError("Missing SHA-256 metadata")
            lines.append(f"# Published {min(item['upload_time_iso_8601'] for item in wheels)}")
            lines.append(f"{name}=={version} \\")
            lines.extend(
                f"    --hash=sha256:{digest}" + (" \\" if i < len(hashes) - 1 else "")
                for i, digest in enumerate(hashes)
            )
        (ROOT / "engine" / filename).write_text("\n".join(lines) + "\n")
        print(filename)


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        sys.exit(str(error))
